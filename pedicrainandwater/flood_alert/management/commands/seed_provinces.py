class Command(BaseCommand):
    help = 'Seed database with all Thai provinces and their coordinates'

    def handle(self, *args, **options):
        created = 0
        updated = 0
        seen = set()

        for name_th, name_en, lat, lon, region in THAI_PROVINCES:
            if name_th in seen:
                continue
            seen.add(name_th)

            obj, is_created = Province.objects.update_or_create(
                name_th=name_th,
                defaults={
                    'name_en': name_en,
                    'latitude': lat,
                    'longitude': lon,
                    'region': region,
                }
            )
            if is_created:
                created += 1
            else:
                updated += 1

        self.stdout.write(
            self.style.SUCCESS(
                f'✅ Seeded {created} new + {updated} updated provinces ({created + updated} total)'
            )
        )
